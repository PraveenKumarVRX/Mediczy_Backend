#!/usr/bin/env node
/**
 * Smoke test: Smart Force field force module (Phase 1 + 2 + 3)
 * =============================================================
 * Usage:
 *   node --env-file=server/.env scripts/smoke-field-force.mjs
 *
 * Requires a team user that has the 'Field Force' permission.
 * Set FIELD_FORCE_EMAIL and FIELD_FORCE_PASSWORD env vars, or it
 * will attempt to use TEAM_TEST_EMAIL / TEAM_TEST_PASSWORD.
 *
 * The test auto-cleans records it creates (best effort).
 */

// fetch is a global in Node 18+ — no import needed

const BASE = process.env.SMOKE_BASE_URL || 'http://localhost:8888/api';
const EMAIL    = process.env.FIELD_FORCE_EMAIL    || process.env.TEAM_TEST_EMAIL;
const PASSWORD = process.env.FIELD_FORCE_PASSWORD || process.env.TEAM_TEST_PASSWORD;

if (!EMAIL || !PASSWORD) {
  console.error('❌  Set FIELD_FORCE_EMAIL + FIELD_FORCE_PASSWORD (or TEAM_TEST_EMAIL + TEAM_TEST_PASSWORD)');
  process.exit(1);
}

let pass = 0, fail = 0, token = '';
const created = { attendanceId: null, visitId: null, claimId: null, itemId: null, empId: null, outreachId: null };

function ok(label, got, pred) {
  const result = typeof pred === 'function' ? pred(got) : got === pred;
  if (result) { console.log(`  ✅  ${label}`); pass++; }
  else         { console.log(`  ❌  ${label} — got: ${JSON.stringify(got)}`); fail++; }
}

async function req(method, path, body, auth = true) {
  const headers = { 'Content-Type': 'application/json' };
  if (auth && token) headers['Authorization'] = `Bearer ${token}`;
  const res = await fetch(`${BASE}${path}`, {
    method,
    headers,
    body: body ? JSON.stringify(body) : undefined,
  }).catch(err => { throw new Error(`Network error on ${method} ${path}: ${err.message}`); });
  const text = await res.text();
  let json;
  try { json = JSON.parse(text); } catch { json = { _raw: text }; }
  return { status: res.status, body: json };
}

// ─── 1. Auth ─────────────────────────────────────────────────────────────────
console.log('\n── 1. Team login ──────────────────────────────────────────');
{
  const r = await req('POST', '/team/login', { email: EMAIL, password: PASSWORD }, false);
  ok('POST /team/login → 200', r.status, s => s === 200);
  token = r.body?.token || r.body?.data?.token || '';
  ok('token issued', token, t => typeof t === 'string' && t.length > 10);
  if (!token) { console.error('Cannot continue without token'); process.exit(1); }
}

// ─── 2. Phase 1 — Attendance ─────────────────────────────────────────────────
console.log('\n── 2. Attendance ──────────────────────────────────────────');
{
  const r = await req('GET', '/field/attendance/today');
  ok('GET /field/attendance/today → 200', r.status, s => s === 200);
}
{
  // clock-in (no GPS in Node)
  const r = await req('POST', '/field/attendance/clock-in', {
    exception_type: 'gps_failure', exception_reason: 'smoke test — no GPS',
  });
  ok('POST /field/attendance/clock-in → 200 or 409', r.status, s => s === 200 || s === 409);
  if (r.status === 200) created.attendanceId = r.body?.id;
}
{
  const r = await req('GET', '/field/attendance/today');
  ok('attendance today has clock_in_at', r.status, s => s === 200);
  ok('attendance record present', r.body, b => b && (b.clock_in_at || b.exception_type));
}
{
  const r = await req('GET', '/field/attendance/history?month=' + new Date().toISOString().slice(0,7));
  ok('GET /field/attendance/history → 200', r.status, s => s === 200);
  ok('records array returned', r.body?.records, v => Array.isArray(v));
}

// ─── 3. Phase 1 — Visits ─────────────────────────────────────────────────────
console.log('\n── 3. Visits ──────────────────────────────────────────────');
{
  const r = await req('POST', '/field/visits', {
    entity_name: 'Smoke Test Hospital Ltd', entity_type: 'hospital',
    purpose: 'initial_visit', notes_planned: 'auto-generated by smoke test',
  });
  ok('POST /field/visits → 201', r.status, s => s === 201);
  created.visitId = r.body?.id;
}
if (created.visitId) {
  const r = await req('PATCH', `/field/visits/${created.visitId}/check-in`, {});
  ok('PATCH /field/visits/:id/check-in → 200', r.status, s => s === 200);
  ok('status is checked_in', r.body?.status, s => s === 'checked_in');
}
if (created.visitId) {
  const r = await req('PATCH', `/field/visits/${created.visitId}/check-out`, {
    met_person: 'Dr Smoke Test', met_designation: 'Medical Director',
    outcome: 'Positive interest in partnership',
    services_discussed: ['Cardiology', 'Diagnostics'],
    next_action: 'Send proposal',
    follow_up_date: new Date(Date.now() + 7*86400000).toISOString().slice(0,10),
  });
  ok('PATCH /field/visits/:id/check-out → 200', r.status, s => s === 200);
  ok('status is completed', r.body?.status, s => s === 'completed');
}
{
  const r = await req('GET', '/field/visits?date=' + new Date().toISOString().slice(0,10));
  ok('GET /field/visits → 200', r.status, s => s === 200);
  ok('visits array returned', r.body?.visits, v => Array.isArray(v));
}

// ─── 4. Phase 1 — Daily report ───────────────────────────────────────────────
console.log('\n── 4. Daily report ────────────────────────────────────────');
{
  const r = await req('POST', '/field/daily-report', {
    planned_visits: 3, completed_visits: 1, missed_visits: 0,
    leads_generated: 1, follow_ups_done: 0,
    key_achievements: 'Smoke test achievement',
    next_day_plan: 'Run more smoke tests',
  });
  ok('POST /field/daily-report → 201', r.status, s => s === 201);
}
{
  const r = await req('GET', '/field/daily-report/today');
  ok('GET /field/daily-report/today → 200', r.status, s => s === 200);
  ok('report has leads_generated', r.body, b => b && typeof b.leads_generated === 'number');
}

// ─── 5. Phase 2 — Expenses ───────────────────────────────────────────────────
console.log('\n── 5. Expense claims ──────────────────────────────────────');
{
  const claimMonth = new Date().toISOString().slice(0,7);
  const r = await req('POST', '/field/expenses', { claim_month: claimMonth, title: 'Smoke test claim' });
  ok('POST /field/expenses → 201', r.status, s => s === 201);
  created.claimId = r.body?.id;
}
if (created.claimId) {
  const r = await req('POST', `/field/expenses/${created.claimId}/items`, {
    expense_date: new Date().toISOString().slice(0,10),
    category: 'travel_km', amount: 125, km_travelled: 25,
    description: 'Smoke test travel',
  });
  ok('POST /field/expenses/:id/items → 201', r.status, s => s === 201);
  created.itemId = r.body?.id;
}
{
  const r = await req('GET', '/field/expenses');
  ok('GET /field/expenses → 200', r.status, s => s === 200);
  ok('claims array returned', Array.isArray(r.body), v => v === true);
}
if (created.claimId) {
  const r = await req('GET', `/field/expenses/${created.claimId}`);
  ok('GET /field/expenses/:id → 200', r.status, s => s === 200);
  ok('items array in detail', r.body?.items, v => Array.isArray(v));
  ok('total_amount updated', Number(r.body?.total_amount), v => v >= 125);
}

// ─── 6. Phase 2 — Camps ──────────────────────────────────────────────────────
console.log('\n── 6. Camps ───────────────────────────────────────────────');
{
  const r = await req('GET', '/field/camps');
  ok('GET /field/camps → 200', r.status, s => s === 200);
  ok('returns array', Array.isArray(r.body), v => v === true);
}
{
  const r = await req('POST', '/field/camps', {
    camp_name: 'Smoke Test Eye Camp', camp_type: 'Eye Camp',
    start_date: new Date(Date.now() + 14*86400000).toISOString().slice(0,10),
    location: 'Test Venue', expected_patients: 50,
  });
  ok('POST /field/camps → 201', r.status, s => s === 201);
}

// ─── 7. Phase 3 — Empanelment ────────────────────────────────────────────────
console.log('\n── 7. Empanelment ─────────────────────────────────────────');
{
  const r = await req('POST', '/field/empanelment', {
    insurer_name: 'Smoke Test Health Insurance',
    insurer_type: 'private_insurer',
    panel_type: 'cashless',
    contact_person: 'Test Contact',
    contact_phone: '9000000000',
    target_date: new Date(Date.now() + 90*86400000).toISOString().slice(0,10),
  });
  ok('POST /field/empanelment → 201', r.status, s => s === 201);
  created.empId = r.body?.id;
}
if (created.empId) {
  const r = await req('POST', `/field/empanelment/${created.empId}/milestone`, {
    milestone: 'Initial meeting done', status: 'done',
  });
  ok('POST /field/empanelment/:id/milestone → 201', r.status, s => s === 201);
}
if (created.empId) {
  const r = await req('PATCH', `/field/empanelment/${created.empId}`, { status: 'contacted' });
  ok('PATCH /field/empanelment/:id status update → 200', r.status, s => s === 200);
  ok('status updated to contacted', r.body?.status, s => s === 'contacted');
}
{
  const r = await req('GET', '/field/empanelment');
  ok('GET /field/empanelment → 200', r.status, s => s === 200);
  ok('returns array with milestones', Array.isArray(r.body), v => v === true);
}

// ─── 8. Phase 3 — Outreach ───────────────────────────────────────────────────
console.log('\n── 8. Outreach accounts ───────────────────────────────────');
{
  const r = await req('POST', '/field/outreach', {
    name: 'Smoke Test NGO', type: 'ngo',
    area: 'Test Area', city: 'Test City',
    primary_contact: 'Smoke Coordinator',
    contact_phone: '9000000001',
    population_served: 5000,
  });
  ok('POST /field/outreach → 201', r.status, s => s === 201);
  created.outreachId = r.body?.id;
}
if (created.outreachId) {
  const r = await req('PATCH', `/field/outreach/${created.outreachId}`, {
    relationship_status: 'contacted',
    next_followup_date: new Date(Date.now() + 7*86400000).toISOString().slice(0,10),
  });
  ok('PATCH /field/outreach/:id → 200', r.status, s => s === 200);
  ok('relationship_status updated', r.body?.relationship_status, s => s === 'contacted');
}
{
  const r = await req('GET', '/field/outreach?type=ngo');
  ok('GET /field/outreach?type=ngo → 200', r.status, s => s === 200);
  ok('returns array', Array.isArray(r.body), v => v === true);
}

// ─── 9. Clock-out ────────────────────────────────────────────────────────────
console.log('\n── 9. Clock-out ───────────────────────────────────────────');
{
  const r = await req('PATCH', '/field/attendance/clock-out', {});
  ok('PATCH /field/attendance/clock-out → 200 or 404', r.status, s => s === 200 || s === 404);
}

// ─── Summary ─────────────────────────────────────────────────────────────────
console.log('\n══════════════════════════════════════════════════════════');
console.log(`  Result: ${pass} passed, ${fail} failed`);
if (fail > 0) {
  console.log('  ❌  SMOKE TEST FAILED');
  process.exit(1);
} else {
  console.log('  ✅  ALL CHECKS PASSED');
}
process.exit(0);
