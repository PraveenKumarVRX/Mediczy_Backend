// Run against a disposable local cluster only. Never use application DB config.
import assert from 'node:assert/strict';
import pg from 'pg';
import { userInfo } from 'node:os';
import { crmQuery } from '../../services/crm/scoped-query.js';
import { up as migrate } from '../../migrations/20261024000000-crm-report-remediation.migration.js';
import { recordCRMChange } from '../../services/crm/record-change.js';
import { validateDeal, validEmail, marketingRecordReference } from '../../services/crm/validation.js';
const options = { host: '127.0.0.1', port: 55490, user: userInfo().username, ssl: false };
const admin = new pg.Pool({ ...options, database:'postgres' });
const database = `crm_report_isolation_${process.pid}`;
await admin.query(`CREATE DATABASE ${database}`);
const db = new pg.Pool({ ...options, database, max:1 });
const a = { id: 1, tenantUid: 'HAAAAA' }, b = { id: 2, tenantUid: 'HBBBBB' };
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
try {
  await db.query(`CREATE TABLE crm_leads (id int, name text, score int);
    CREATE TABLE crm_leads_v2 (legacy_lead_id int, tenant_uid text);
    CREATE TABLE crm_deals (id int, tenant_uid text, value numeric, probability int);
    CREATE TABLE crm_activities (id int, tenant_uid text, lead_id int);
    CREATE TABLE crm_marketing_lists (id int, name text, created_by int);
    CREATE TABLE crm_marketing_list_members (id int, list_id int);
    CREATE TABLE crm_ai_email_communications (id int, created_by int, status text);
    INSERT INTO crm_leads VALUES (1,'Tenant A',0),(2,'Tenant B',90);
    INSERT INTO crm_leads_v2 VALUES (1,'HAAAAA'),(2,'HBBBBB');
    INSERT INTO crm_deals VALUES (1,'HAAAAA',5000,50),(2,'HBBBBB',90000,90);
    INSERT INTO crm_marketing_lists VALUES (1,'A list',1),(2,'B list',2);
    INSERT INTO crm_marketing_list_members VALUES (1,1),(2,2);
    INSERT INTO crm_ai_email_communications VALUES (1,1,'draft'),(2,2,'draft');`);
  check((await crmQuery(a, 'SELECT id FROM crm_leads ORDER BY id LIMIT 50', [], db)).rows, [{ id: 1 }]);
  check((await crmQuery(b, 'SELECT id FROM crm_leads ORDER BY id LIMIT 50', [], db)).rows, [{ id: 2 }]);
  check((await crmQuery(a, 'SELECT SUM(value)::int AS total FROM crm_deals', [], db)).rows, [{ total: 5000 }]);
  check((await crmQuery(a, 'SELECT * FROM crm_leads WHERE id=$1', [2], db)).rows, []);
  check((await crmQuery(a, 'UPDATE crm_leads SET score=$1 WHERE id=$2 RETURNING id', [99,2], db)).rows, []);
  check((await crmQuery(a, 'UPDATE crm_leads SET score=$1 WHERE id=$2 RETURNING score', [40,1], db)).rows, [{ score: 40 }]);
  check((await crmQuery(a, 'SELECT l.id, COUNT(m.id)::int AS members FROM crm_marketing_lists l LEFT JOIN crm_marketing_list_members m ON m.list_id=l.id GROUP BY l.id', [], db)).rows, [{ id: 1, members: 1 }]);
  check((await crmQuery(a, 'UPDATE crm_ai_email_communications SET status=$1 WHERE id=$2 RETURNING id', ['sent',2], db)).rows, []);
  await assert.rejects(crmQuery({}, 'SELECT * FROM crm_leads', [], db), /tenant context/); checks++;
  check(validEmail('qa.test.lead@example.com,'), false);
  check(validEmail('qa.test.lead@example.com'), true);
  check(validateDeal({ title:'Deal', value:-5000 }, { creating:true }), 'Deal value must be zero or greater');
  check(validateDeal({ probability:150 }), 'Probability must be between 0 and 100');
  check(validateDeal({ probability:0, value:0 }), null);
  check(validateDeal({ title:'Deal', expected_close:'2026-10-01' }, { creating:true, today:'2026-10-24' }), 'Expected close date cannot be in the past for a new open deal');
  check(marketingRecordReference('/lists/1/import'), {kind:'lists',id:'1'});
  check(marketingRecordReference('/templates'), null);
  assert.throws(() => marketingRecordReference('/lists/1%20/import'), /Invalid/); checks++;
  assert.throws(() => marketingRecordReference('/lists/not-a-number'), /Invalid/); checks++;
  await db.query(`ALTER TABLE crm_leads ADD COLUMN email text, ADD COLUMN deal_id int, ADD COLUMN status text, ADD COLUMN converted_at timestamptz, ADD COLUMN assigned_to int, ADD COLUMN created_by int;
    ALTER TABLE crm_deals ADD COLUMN title text, ADD COLUMN contact_name text, ADD COLUMN contact_email text, ADD COLUMN contact_phone text, ADD COLUMN company text, ADD COLUMN lead_id int, ADD COLUMN created_by int;
    ALTER TABLE crm_leads_v2 ADD COLUMN owner_user_id int, ADD COLUMN identity_id int, ADD COLUMN person_id int;
    ALTER TABLE crm_activities ADD COLUMN type text, ADD COLUMN title text, ADD COLUMN description text, ADD COLUMN deal_id int, ADD COLUMN completed_at timestamptz, ADD COLUMN created_by int;
    CREATE TABLE crm_contacts (id bigserial PRIMARY KEY, name text, email text, phone text, company text, lead_id int, created_by int, tenant_uid text);
    CREATE TABLE crm_audit_log (tenant_id int, entity_type text, entity_id int, event_type text, actor_user_id int, new_value jsonb);
    UPDATE crm_leads SET email='qa@example.invalid', status='new', assigned_to=id, created_by=id;
    UPDATE crm_deals SET contact_name='QA',contact_email='qa@example.invalid',created_by=id,title='QA deal';
    UPDATE crm_leads_v2 SET person_id=legacy_lead_id;`);
  await migrate(db); await migrate(db);
  check((await db.query('SELECT COUNT(*)::int AS count FROM crm_contacts')).rows, [{count:2}]);
  check((await db.query('SELECT id,lead_id FROM crm_deals ORDER BY id')).rows, [{id:1,lead_id:1},{id:2,lead_id:2}]);
  check((await db.query('SELECT COUNT(*)::int AS count FROM crm_deals d JOIN crm_contacts c ON c.id=d.contact_id AND c.tenant_uid=d.tenant_uid')).rows, [{count:2}]);
  await recordCRMChange(db, {...a,tenantId:1}, 'deal', {id:1,title:'QA deal',lead_id:1}, 'updated');
  check((await db.query("SELECT title, completed_at IS NOT NULL AS completed FROM crm_activities WHERE tenant_uid='HAAAAA'")).rows, [{title:'Deal updated: QA deal',completed:true}]);
  check((await db.query('SELECT event_type FROM crm_audit_log')).rows, [{event_type:'updated'}]);
  await db.query(`CREATE TABLE tenants (id int PRIMARY KEY, unique_id text); CREATE TABLE users (id int PRIMARY KEY, tenant_id int);
    ALTER TABLE crm_marketing_list_members ADD COLUMN contact_id bigint, ADD COLUMN email text, ADD COLUMN first_name text, ADD COLUMN last_name text, ADD COLUMN company text;
    INSERT INTO tenants VALUES (1,'HAAAAA'),(2,'HBBBBB'); INSERT INTO users VALUES (1,1),(2,2);
    UPDATE crm_marketing_list_members SET email='import@example.invalid',first_name='Imported';`);
  await migrate(db); await migrate(db);
  check((await db.query("SELECT COUNT(*)::int AS count FROM crm_contacts WHERE email='import@example.invalid'")).rows, [{count:2}]);
  check((await db.query('SELECT COUNT(*)::int AS count FROM crm_marketing_list_members m JOIN crm_marketing_lists l ON l.id=m.list_id JOIN crm_contacts c ON c.id=m.contact_id JOIN users u ON u.id=l.created_by JOIN tenants t ON t.id=u.tenant_id WHERE c.tenant_uid=t.unique_id')).rows, [{count:2}]);
  check((await crmQuery(a, 'SELECT id FROM crm_contacts WHERE tenant_uid=$1', ['HBBBBB'], db)).rows, []);
  console.log(JSON.stringify({ success:true, checks, database:'disposable local PostgreSQL', liveDataModified:false }));
} finally { await db.end(); await admin.query(`DROP DATABASE ${database}`); await admin.end(); }
