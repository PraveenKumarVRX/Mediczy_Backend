#!/usr/bin/env node
/**
 * Test care team booking alert email (noreply@mediqzy.com -> care@mysmarthealth.in)
 *
 * Usage:
 *   node scripts/test-care-team-booking-alert.mjs              # unit + SMTP inspect
 *   node scripts/test-care-team-booking-alert.mjs --send         # send live test email
 *   node scripts/test-care-team-booking-alert.mjs --send --to you@example.com
 */

import dotenv from 'dotenv';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverRoot = join(__dirname, '..');

for (const envFile of ['.env', '.env.production.local', '.env.testing']) {
  dotenv.config({ path: join(serverRoot, envFile) });
  dotenv.config({ path: join(serverRoot, '..', envFile) });
}

const args = process.argv.slice(2);
const shouldSend = args.includes('--send');
const toOverrideIndex = args.indexOf('--to');
const toOverride = toOverrideIndex >= 0 ? args[toOverrideIndex + 1] : null;

if (toOverride) {
  process.env.CARE_TEAM_EMAIL = toOverride;
}

const {
  normalizeCareTeamBookingDetails,
  resolveSmtpConfigs,
  sendCareTeamBookingAlert
} = await import('../services/care-team-notification.service.js');

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function runNormalizationTests() {
  console.log('\n=== Normalization tests ===');
  const sample = normalizeCareTeamBookingDetails({
    appointment: {
      id: 12345,
      patientName: 'Test Patient',
      patientEmail: 'patient@example.com',
      patientPhone: '+919876543210',
      doctorName: 'Dr. Test Doctor',
      specialization: 'General Medicine',
      appointmentDate: '2026-06-15',
      appointmentTime: '10:30',
      consultationType: 'online',
      status: 'pending',
      paymentStatus: 'pending',
      symptoms: ['fever', 'headache'],
      notes: 'Test booking'
    },
    bookingSource: 'test-script'
  });

  assert(sample.appointmentId === 12345, 'appointmentId');
  assert(sample.patientName === 'Test Patient', 'patientName');
  assert(sample.patientEmail === 'patient@example.com', 'patientEmail');
  assert(sample.symptoms === 'fever, headache', 'symptoms array join');
  assert(sample.bookingSource === 'test-script', 'bookingSource');
  console.log('✅ normalizeCareTeamBookingDetails');
}

function redactConfig(config) {
  return {
    source: config.source,
    host: config.host,
    port: config.port,
    secure: config.secure,
    user: config.user,
    fromEmail: config.fromEmail,
    fromName: config.fromName,
    replyTo: config.replyTo,
    password: config.pass ? '[set]' : '[missing]'
  };
}

async function inspectSmtpConfigs() {
  console.log('\n=== SMTP inspect (noreply@mediqzy.com) ===');
  console.log('Recipient (CARE_TEAM_EMAIL):', process.env.CARE_TEAM_EMAIL || 'care@mysmarthealth.in');
  console.log('Sender (CARE_TEAM_SMTP_FROM):', process.env.CARE_TEAM_SMTP_FROM || 'noreply@mediqzy.com');

  const configs = await resolveSmtpConfigs();
  if (!configs.length) {
    console.log('❌ No SMTP config found for noreply@mediqzy.com');
    console.log('   Add email_configs / email_settings row, or set:');
    console.log('   NOREPLY_SMTP_USER=noreply@mediqzy.com');
    console.log('   NOREPLY_SMTP_PASSWORD=...');
    return false;
  }

  configs.forEach((cfg, index) => {
    console.log(`✅ Config ${index + 1}:`, JSON.stringify(redactConfig(cfg), null, 2));
  });
  return true;
}

async function sendTestAlert() {
  console.log('\n=== Live send test ===');
  const result = await sendCareTeamBookingAlert({
    appointment: {
      id: 'TEST-' + Date.now(),
      patientName: 'Test Patient (Care Alert Smoke Test)',
      patientEmail: 'test-patient@example.com',
      patientPhone: '+919999999999',
      doctorName: 'Dr. Smoke Test',
      specialization: 'General Medicine',
      appointmentDate: new Date().toISOString().slice(0, 10),
      appointmentTime: '11:00',
      consultationType: 'online',
      status: 'pending',
      paymentStatus: 'pending',
      symptoms: 'Automated smoke test — please ignore',
      notes: 'Generated by scripts/test-care-team-booking-alert.mjs'
    },
    bookingSource: 'test-script'
  });

  if (!result.sent) {
    throw new Error(`Send failed: ${result.reason || 'unknown'}`);
  }

  console.log('✅ Test alert sent');
  console.log('   to:', result.to);
  console.log('   from:', result.from);
  console.log('   via:', result.source);
  return result;
}

async function main() {
  console.log('Care team booking alert — test runner');
  runNormalizationTests();

  const hasSmtp = await inspectSmtpConfigs();
  if (!shouldSend) {
    console.log('\nDry run complete. Pass --send to deliver a live test email.');
    process.exit(hasSmtp ? 0 : 1);
  }

  if (!hasSmtp) {
    process.exit(1);
  }

  await sendTestAlert();
  console.log('\nAll tests passed.');
}

main()
  .then(async () => {
    try {
      const { default: sharedPool } = await import('../db/pgPool.js');
      await sharedPool.end();
    } catch (_) {
      /* ignore */
    }
    process.exit(0);
  })
  .catch(async (error) => {
    console.error('\n❌ Test failed:', error.message);
    try {
      const { default: sharedPool } = await import('../db/pgPool.js');
      await sharedPool.end();
    } catch (_) {
      /* ignore */
    }
    process.exit(1);
  });
