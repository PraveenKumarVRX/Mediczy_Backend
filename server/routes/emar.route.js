import express from 'express';
import { authUser } from '../middleware/auth.middleware.js';
import { createMedicationOrder, recordAdministration, validateAdministration, getActiveOrders, getAdministrationHistory, getDueMedications, updateOrderStatus, preparePrnDose, recordInfusionEvent, listInfusionEvents, authorizeInfusionRate } from '../services/emar.service.js';
import { nursingContext } from '../services/nursing-context.service.js';
import { nursingHandler } from './nursing-http.js';
import { prescriptionSafetyGate } from '../services/prescription-safety.service.js';
const router = express.Router();
router.use(authUser);
const safetyOnOrder = prescriptionSafetyGate('emar.order', req => ({ patientId: req.body?.patientId, medications: [{ name: req.body?.drugName, dosage: [req.body?.dose, req.body?.doseUnit].filter(Boolean).join(' ') }] }), { issuing: true });
router.post('/orders', safetyOnOrder, nursingHandler(req => createMedicationOrder(req.body), 201));
router.get('/orders/:admissionId', nursingHandler(req => getActiveOrders(req.params.admissionId, nursingContext().organizationId)));
router.post('/validate-administration', nursingHandler(async (req) => {
    const { order, admission, witness, ...result } = await validateAdministration(req.body);
    return result;
}));
const administer = nursingHandler(async (req) => {
    const input = { ...req.body, ...(req.params.orderId ? { orderId: Number(req.params.orderId) } : {}), idempotencyKey: req.get('Idempotency-Key') };
    return recordAdministration(input);
}, 201);
router.post('/administer', administer);
router.post('/:orderId/administer', administer);
router.get('/due', nursingHandler(req => getDueMedications(nursingContext().organizationId, req.query)));
router.get('/due/:admissionId', nursingHandler(req => getDueMedications(nursingContext().organizationId, { ...req.query, admissionId: req.params.admissionId })));
router.get('/history/:admissionId', nursingHandler(req => getAdministrationHistory(req.params.admissionId)));
router.post('/:orderId/hold', nursingHandler(req => updateOrderStatus(nursingContext().organizationId, req.params.orderId, 'on_hold', req.body.holdReason)));
router.put('/orders/:id/hold', nursingHandler(req => updateOrderStatus(nursingContext().organizationId, req.params.id, 'on_hold', req.body.reason)));
router.put('/orders/:id/discontinue', nursingHandler(req => updateOrderStatus(nursingContext().organizationId, req.params.id, 'discontinued', req.body.reason)));
router.post('/orders/:id/prn-slot', nursingHandler(req => preparePrnDose(req.params.id, { ...req.body, idempotencyKey: req.get('Idempotency-Key') }), 201));
router.post('/infusions', nursingHandler(req => recordInfusionEvent({ ...req.body, idempotencyKey: req.get('Idempotency-Key') }), 201));
router.get('/infusions/:admissionId', nursingHandler(req => listInfusionEvents(req.params.admissionId)));
router.post('/orders/:id/infusion-rate', nursingHandler(req => authorizeInfusionRate(req.params.id, req.body)));
export default router;
