#!/bin/bash

echo "🏥 Dr. Kumar Prescription Sharing Demo"
echo "======================================"
echo ""

# Login
echo "🔐 Step 1: Logging in as Dr. Kumar..."
TOKEN=$(curl -s -X POST http://localhost:8000/api/doctors/login \
  -H 'Content-Type: application/json' \
  -d '{"email":"drkumar.surgery@mediczy.com","password":"DrKumar@2025"}' | jq -r .token)

echo "✅ Logged in successfully"
echo ""

PRESCRIPTION_ID="RX-MJFXG1H6-PDJHU"

# Demonstrate each sharing method
echo "📋 Prescription: $PRESCRIPTION_ID"
echo "   Patient: Rahul Verma (Post-op cholecystectomy)"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📲 METHOD 1: Share on WhatsApp"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

WHATSAPP=$(curl -s -X POST \
  "http://localhost:8000/api/prescriptions/$PRESCRIPTION_ID/share/whatsapp/9876512345" \
  -H "Authorization: Bearer $TOKEN")

echo ""
echo "✅ WhatsApp link generated:"
echo "   Phone: $(echo "$WHATSAPP" | jq -r .phoneNumber)"
echo ""
echo "📱 Click this link to send via WhatsApp:"
echo "   $(echo "$WHATSAPP" | jq -r .whatsappUrl | head -c 80)..."
echo ""
echo "💬 Message preview:"
echo "   🏥 Medical Prescription"
echo "   Dear Rahul Verma,"
echo "   Your prescription has been generated by Kumar Sharma."
echo "   📋 Prescription ID: $PRESCRIPTION_ID"
echo "   📥 Download PDF: https://mediczy.com/api/prescriptions/$PRESCRIPTION_ID/pdf"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🖨️  METHOD 2: Print Prescription"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

curl -s "http://localhost:8000/api/prescriptions/$PRESCRIPTION_ID/html" \
  -H "Authorization: Bearer $TOKEN" \
  -o /tmp/print-ready.html

echo ""
echo "✅ Print-ready HTML generated"
echo "   File: /tmp/print-ready.html"
echo ""
echo "🌐 To print:"
echo "   1. Open URL: http://localhost:8000/api/prescriptions/$PRESCRIPTION_ID/html"
echo "   2. Click 'Print Prescription' button"
echo "   3. Or press Ctrl+P"
echo "   4. Select printer or 'Save as PDF'"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📄 METHOD 3: Download PDF"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

curl -s "http://localhost:8000/api/prescriptions/$PRESCRIPTION_ID/pdf" \
  -H "Authorization: Bearer $TOKEN" \
  -o /tmp/download.pdf 2>/dev/null

FILE_TYPE=$(file /tmp/download.pdf | grep -o "HTML\|PDF")
SIZE=$(ls -lh /tmp/download.pdf | awk '{print $5}')

echo ""
echo "📥 Downloaded: /tmp/download.pdf ($SIZE)"
echo "   Type: $FILE_TYPE"
echo ""
if [[ "$FILE_TYPE" == "HTML" ]]; then
  echo "💡 Tip: Open the HTML file in browser and print to PDF"
  echo "   The HTML version is fully formatted and print-ready!"
fi
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✨ Prescription Features"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "The prescription includes:"
echo "  ✅ Professional EMR header (blue gradient)"
echo "  ✅ Doctor credentials: Kumar Sharma, MS (General Surgery), MBBS"
echo "  ✅ Specialty: General Surgery"
echo "  ✅ Clinic details with logo and seal"
echo "  ✅ Patient info: Rahul Verma, 45 yrs, Male"
echo "  ✅ Vitals: BP 128/84, Pulse 76, Temp 98.2°F"
echo "  ✅ Diagnosis: Post-op laparoscopic cholecystectomy"
echo "  ✅ Medications with dosage and duration"
echo "  ✅ Instructions and advice"
echo "  ✅ Digital signature section"
echo "  ✅ Official clinic seal (circular)"
echo "  ✅ EMR certification badge"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🎯 Quick Access URLs"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
